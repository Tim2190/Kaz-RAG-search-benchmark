"""
Токенизатор, осведомлённый о казахской кириллице.

Казахский алфавит добавляет к русской кириллице специфические буквы:
ә і ң ғ ү ұ қ ө һ (и их заглавные). Базовая токенизация в RAG-системах
часто рвёт или выкидывает их — это одна из причин «слепоты» на казахском.
Здесь токенизатор явно сохраняет весь кириллический диапазон + латиницу
и цифры (для смешанных текстов гос. релизов).
"""

from __future__ import annotations

import re
from typing import List

# Кириллица (U+0400–U+04FF покрывает и русские, и казахские буквы) + латиница + цифры
_TOKEN_RE = re.compile(r"[0-9a-zA-ZЀ-ӿ]+", re.UNICODE)


def tokenize(text: str, lowercase: bool = True) -> List[str]:
    """Разбивает текст на токены, сохраняя казахские буквы."""
    if not text:
        return []
    if lowercase:
        text = text.lower()
    return _TOKEN_RE.findall(text)
