"""
Транслитерация казахской КИРИЛЛИЦЫ → ЛАТИНИЦА по официальному стандарту 2021 г.

Зачем это в бенчмарке
---------------------
Гипотеза слоя input-preprocessing: токенизаторы «сломанных» моделей
(byte-fallback: Cohere embed-v4, Qwen3) рвут казахскую кириллицу на байтовый
мусор. Латиницу те же токенизаторы могли видеть чаще (англоязычный претрейн),
поэтому транслитерация МОЖЕТ починить вход без дообучения. Здесь — только
детерминированное текст-в-текст преобразование; проверка гипотезы в
input-preprocessing/code/run_preprocessing.py.

Стандарт
--------
Таблица — официальный казахский латинский алфавит, утверждённый в апреле 2021 г.
(умляут/макрон/бревис-версия; Указ Президента РК). Ключевые соответствия,
зафиксированные планом и стандартом:

    ә→ä  ғ→ğ  қ→q  ң→ñ  ө→ö  ұ→ū  ү→ü  һ→h  і→i  ш→ş  ж→j

ВАЖНО (воспроизводимость): таблица зашита в код целиком и явно — никакой сети,
никакой внешней библиотеки, которая может молча поменять версию. Это
детерминированный стандарт, а НЕ самодельная схема: каждое соответствие ниже
сверяется с указанным алфавитом 2021 г.

Для нескольких кириллических букв, которых нет в исконном казахском (русские
заимствования: ц, ч, щ, ю, я, ё, ъ, ь, и, й), стандарт не задаёт однозначной
одной буквы — для них взяты ДОКУМЕНТИРОВАННЫЕ ниже устойчивые соответствия
(диграфы / семивокалы). Главное для эксперимента — детерминизм и симметрия:
запрос и корпус транслитерируются ОДНОЙ И ТОЙ ЖЕ функцией.
"""

from __future__ import annotations

# Базовая таблица в нижнем регистре. Заглавные выводятся через .upper()
# результата (латиница умляутов/диакритик корректно поднимается в Python).
#
# Порядок: исконно казахские буквы (ядро стандарта 2021) сверху, затем
# русско-заимствованные с документированным выбором соответствия.
_MAP_LOWER = {
    # ── гласные/согласные ядра казахского алфавита ──
    "а": "a",
    "ә": "ä",   # стандарт 2021
    "б": "b",
    "в": "v",
    "г": "g",
    "ғ": "ğ",   # стандарт 2021
    "д": "d",
    "е": "e",
    "ж": "j",   # стандарт 2021
    "з": "z",
    "к": "k",
    "қ": "q",   # стандарт 2021
    "л": "l",
    "м": "m",
    "н": "n",
    "ң": "ñ",   # стандарт 2021
    "о": "o",
    "ө": "ö",   # стандарт 2021
    "п": "p",
    "р": "r",
    "с": "s",
    "т": "t",
    "у": "u",
    "ұ": "ū",   # стандарт 2021 (макрон)
    "ү": "ü",   # стандарт 2021
    "ф": "f",
    "х": "h",
    "һ": "h",   # стандарт 2021 (совпадает с х → h)
    "ы": "y",   # стандарт 2021
    "і": "i",   # стандарт 2021 (план: і→i)
    "ш": "ş",   # стандарт 2021
    # ── русско-заимствованные: документированный выбор ──
    # (исконных казахских слов с этими буквами нет; берём устойчивые
    #  транслитерационные соответствия, чтобы преобразование оставалось
    #  обратимым по смыслу и детерминированным)
    "и": "i",   # близка к і; для IR сводим к i (снижает разреженность)
    "й": "y",   # семивокал
    "ц": "ts",
    "ч": "ch",
    "щ": "şş",
    "э": "e",
    "ю": "iu",
    "я": "ia",
    "ё": "io",
    "ъ": "",    # твёрдый знак — опускается
    "ь": "",    # мягкий знак — опускается
}


def _build_full_map() -> dict:
    """Достраивает заглавные варианты из нижнего регистра."""
    full = {}
    for cyr, lat in _MAP_LOWER.items():
        full[cyr] = lat
        # заглавная кириллица → заглавная латиница (capitalize диграфов: Ts, Ch)
        full[cyr.upper()] = lat.upper() if len(lat) <= 1 else lat.capitalize()
    return full


_FULL_MAP = _build_full_map()


def transliterate(text: str) -> str:
    """
    Кириллица → латиница по стандарту 2021. Символы вне таблицы (латиница,
    цифры, пунктуация, пробелы) проходят без изменений.

    Детерминированно и без побочных эффектов: одна и та же строка всегда даёт
    один и тот же результат — это критично для симметрии запрос/корпус.
    """
    if not text:
        return text
    return "".join(_FULL_MAP.get(ch, ch) for ch in text)
